-- Run in Supabase SQL Editor. The public website can INSERT answers only.
-- Authenticated dashboard owner can read/delete only rows belonging to their account.
create table if not exists public.garden_answers (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  question text not null,
  answer text not null check (char_length(answer) <= 500),
  owner_id uuid references auth.users(id) default auth.uid()
);
alter table public.garden_answers enable row level security;
-- Visitors are allowed to submit an answer, but cannot read any answer.
create policy "Anyone can submit garden answers" on public.garden_answers
  for insert to anon, authenticated with check (owner_id is null or owner_id = auth.uid());
-- Owner dashboard policies: set the owner's auth user UUID in the SQL below.
-- Replace YOUR_AUTH_USER_UUID with the UUID of the dashboard owner.
create policy "Only garden owner can read answers" on public.garden_answers
  for select to authenticated using (auth.uid() = 'YOUR_AUTH_USER_UUID'::uuid);
create policy "Only garden owner can delete answers" on public.garden_answers
  for delete to authenticated using (auth.uid() = 'YOUR_AUTH_USER_UUID'::uuid);
